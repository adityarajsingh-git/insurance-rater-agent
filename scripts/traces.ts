// Writes the structured output and a readable decision trace for each of the four sample policies.
//
// Input is the committed OCR fixture for each sample (tests/fixtures/ocr/<name>.json), which is the
// same page text the hosted app produces in the browser: pdf.js render at 300 dpi, tesseract.js OCR,
// plus the contrast-enhanced second pass in `enhancedText`. No user answers are applied, so each
// output is what a reviewer sees right after uploading the PDF.
//
// Usage: npx tsx scripts/traces.ts          (rewrites traces/*.json and traces/*.md)
//        npx tsx scripts/traces.ts --check  (exits 1 if the committed files are stale)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { analyse } from '../src/core/agent';
import type { AnalysisResult, Citation, Fact, PageText, RateComponent } from '../src/core/types';

export const SAMPLES = [
  'pvt-car-satp-go-digit',
  'pvt-car-comprehensive-reliance',
  'pvt-car-comprehensive-hdfc-ergo',
  'pvt-car-satp-tata-aig',
] as const;

/** The analysis with its wall-clock timestamp removed, so the committed file is reproducible. */
export function sampleOutput(name: string): Omit<AnalysisResult, 'analysedAt'> {
  const pages: PageText[] = JSON.parse(readFileSync(`tests/fixtures/ocr/${name}.json`, 'utf8'));
  const { analysedAt: _ignored, ...rest } = analyse(pages);
  return rest;
}

const esc = (s: unknown) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const clip = (s: string, n = 110) => (s.length > n ? `${s.slice(0, n - 1)}…` : s);

function cite(c: Citation): string {
  const where = [
    c.sheet && c.cell ? `'${c.sheet}'!${c.cell}` : c.sheet ? `'${c.sheet}'` : c.cell,
    c.page !== undefined ? `p.${c.page}` : undefined,
    c.table,
    c.row && `row "${c.row}"`,
    c.column && `column "${c.column}"`,
  ].filter(Boolean).join(', ');
  return `\`${c.file}\` ${where} = **${esc(c.value)}**: ${esc(c.label)}`;
}

function isFact(v: unknown): v is Fact<unknown> {
  return typeof v === 'object' && v !== null && 'status' in v && 'evidence' in v;
}

function factRows(facts: object, prefix = ''): string[] {
  const rows: string[] = [];
  for (const [key, v] of Object.entries(facts)) {
    if (isFact(v)) {
      const value = Array.isArray(v.value) ? v.value.join(', ') : v.value;
      const ev = v.evidence
        .map((e) => `${e.page !== undefined ? `p.${e.page} ` : ''}(${e.source}) "${clip(esc(e.quote), 90)}"`)
        .join('; ');
      const note = [v.note, v.candidates?.length ? `candidates: ${v.candidates.join(' / ')}` : '']
        .filter(Boolean).join(' ');
      rows.push(`| ${prefix}${key} | ${v.status} | ${esc(value) || '-'} | ${ev || '-'} | ${esc(note) || ''} |`);
    } else if (typeof v === 'object' && v !== null) {
      rows.push(...factRows(v, `${prefix}${key}.`));
    }
  }
  return rows;
}

function component(name: string, c: RateComponent): string[] {
  const out = [
    `### ${name}`,
    '',
    `- **Applicability:** ${c.applicability}`,
    `- **Rate:** ${c.ratePercent === null ? '-' : `${c.ratePercent}%`} of ${c.appliesTo}`,
    `- **Premium base:** ${c.premiumBase === null ? '-' : `₹${c.premiumBase}`}`,
    `- **Expected brokerage:** ${c.expectedBrokerage === null ? '-' : `₹${c.expectedBrokerage}`}`,
    `- **Reason:** ${esc(c.reason)}`,
  ];
  if (c.citations.length) out.push('- **Citations:**', ...c.citations.map((x) => `  - ${cite(x)}`));
  if (c.candidates?.length) {
    out.push('- **Candidates (the answer depends on a fact the policy does not settle):**');
    for (const k of c.candidates) {
      out.push(`  - ${k.ratePercent}% if ${esc(k.assumption)}`, ...k.citations.map((x) => `    - ${cite(x)}`));
    }
  }
  return [...out, ''];
}

export function renderMarkdown(name: string, a: Omit<AnalysisResult, 'analysedAt'>): string {
  const r = a.result;
  const lines = [
    `# Decision trace: ${name}`,
    '',
    `Generated by \`npx tsx scripts/traces.ts\` from \`tests/fixtures/ocr/${name}.json\` (browser-equivalent OCR of \`sample-policies/${name}.pdf\`), engine ${a.engineVersion}, no user answers applied. The full structured output is in [\`${name}.json\`](./${name}.json).`,
    '',
    `**Status:** ${r.status} · **Insurer:** ${r.insurer ?? '-'} · **Confidence:** ${r.confidence.level} (${esc(r.confidence.reason)})`,
    '',
    `**Summary:** ${esc(r.summary)}`,
    '',
    `**Grid:** ${r.grid ? `\`${r.grid.file}\`, ${esc(r.grid.label)}, effective ${esc(r.grid.effective)}` : '-'}`,
    '',
    '## Result',
    '',
    ...component('Own Damage (OD)', r.od),
    ...component('Third Party (TP)', r.tp),
  ];
  if (r.questions.length) {
    lines.push('## Clarifying questions', '');
    for (const q of r.questions) {
      const opts = q.options?.length ? ` Options: ${q.options.map((o) => `\`${o.value}\` (${esc(o.label)})`).join(', ')}.` : '';
      lines.push(`- **${q.fact}:** ${esc(q.question)}${opts}`);
    }
    lines.push('');
  }
  lines.push('## Decision trace', '');
  r.trace.forEach((s, i) => {
    lines.push(`${i + 1}. **${esc(s.title)}** [${s.outcome ?? 'ok'}]: ${esc(s.detail)}`);
    for (const c of s.citations ?? []) lines.push(`   - ${cite(c)}`);
  });
  lines.push(
    '',
    '## Extracted facts',
    '',
    '| Fact | Status | Value | Evidence (page, source, quote) | Note |',
    '|---|---|---|---|---|',
    ...factRows(a.facts),
    '',
  );
  return lines.join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  mkdirSync('traces', { recursive: true });
  let stale = 0;
  for (const name of SAMPLES) {
    const out = sampleOutput(name);
    const files: [string, string][] = [
      [`traces/${name}.json`, `${JSON.stringify(out, null, 2)}\n`],
      [`traces/${name}.md`, renderMarkdown(name, out)],
    ];
    for (const [path, body] of files) {
      if (check) {
        if (!existsSync(path) || readFileSync(path, 'utf8') !== body) {
          console.error(`stale: ${path}`);
          stale++;
        }
      } else writeFileSync(path, body);
    }
    const { od, tp } = out.result;
    console.log(`${name}: ${out.result.status}, OD ${od.applicability} ${od.ratePercent ?? '-'}%, TP ${tp.applicability} ${tp.ratePercent ?? '-'}%`);
  }
  if (stale) process.exit(1);
}

if (process.argv[1]?.endsWith('traces.ts')) main();
